//! `String.prototype.localeCompare`, which the Node tool used to sort project and variable names: ICU's root
//! collation. Names compare first by their letters (case and accents aside), then by their accents, then by case (a
//! small letter before a ligature before a capital). The order of the ASCII characters, of every Latin letter and of
//! the accents is ICU's, read from Node's own answers; anything else is ordered after the Latin letters by its small
//! letter's code point.

use std::cmp::Ordering;

/// The printable ASCII characters (and the whitespace controls) in the order ICU's root collation puts them:
/// whitespace, punctuation, symbols, digits, then letters with each small letter before its capital. Letters share a
/// weight with their other case.
const ICU_ASCII_ORDER: &str =
    "\t\n\x0B\x0C\r _-,;:!?.'\"()[]{}@*/\\&#%`^+<=>|~$0123456789aAbBcCdDeEfFgGhHiIjJkKlLmMnNoOpPqQrRsStTuUvVwWxXyYzZ";

/// Letters are this far apart, so the Latin letters ICU puts on their own fit between them.
const STEP: u32 = 1000;

/// One element of a character's weights: (letters, accents, case). A letters weight of 0 is an accent alone, which
/// counts only from the accents level on; accents are 0 on a letter without one.
type Weight = (u32, u16, u8);

fn ascii_primary(c: char) -> Option<u32> {
    let c = if c.is_ascii_alphabetic() {
        c.to_ascii_lowercase()
    } else {
        c
    };
    ICU_ASCII_ORDER.find(c).map(|index| (index as u32 + 1) * STEP)
}

/// The weights of one character: a letter, then its accents (a letter ICU counts as two gets its accent after the
/// first), none for a control character ICU ignores.
fn collation_weights(c: char, out: &mut Vec<Weight>) {
    if c.is_ascii() {
        if let Some(primary) = ascii_primary(c) {
            out.push((primary, 0, if c.is_ascii_uppercase() { 3 } else { 0 }));
        }
        return;
    }
    if let Some((_, letters, accents, case)) = LATIN_AS_ASCII.iter().find(|(l, _, _, _)| *l == c) {
        for (i, letter) in letters.chars().enumerate() {
            out.push((ascii_primary(letter).unwrap_or(0), 0, *case));
            if i == 0 {
                out.extend(accents.iter().map(|accent| (0, *accent, 0)));
            }
        }
        return;
    }
    if let Some((_, parts)) = LATIN_PARTS.iter().find(|(l, _)| *l == c) {
        let from = out.len();
        for part in parts.chars() {
            collation_weights(part, out);
        }
        // A compatibility form comes after the plain letters at the case level.
        for weight in &mut out[from..] {
            weight.2 = weight.2.max(1);
        }
        return;
    }
    if let Some((_, after, place, accents, case)) = LATIN_OWN.iter().find(|(l, _, _, _, _)| *l == c) {
        let primary = ascii_primary(*after).unwrap_or(0) + 1 + u32::from(*place);
        out.push((primary, 0, *case));
        out.extend(accents.iter().map(|accent| (0, *accent, 0)));
        return;
    }
    // An accent written as a mark of its own: an accent of the letter before it.
    if let Some((_, accent)) = MARKS.iter().find(|(m, _)| *m == c) {
        out.push((0, *accent, 0));
        return;
    }
    if c.is_control() || ('\u{300}'..='\u{36F}').contains(&c) {
        return;
    }
    let lower = c.to_lowercase().next().unwrap_or(c);
    out.push((1_000_000 + lower as u32, 0, if lower != c { 3 } else { 0 }));
}

/// `a.localeCompare(b)`.
pub(super) fn locale_compare(a: &str, b: &str) -> Ordering {
    let weights = |s: &str| {
        let mut out = Vec::new();
        for c in s.chars() {
            collation_weights(c, &mut out);
        }
        out
    };
    let (wa, wb) = (weights(a), weights(b));
    let letters = |w: &[Weight]| w.iter().map(|w| w.0).filter(|p| *p != 0).collect::<Vec<_>>();
    let accents = |w: &[Weight]| w.iter().map(|w| w.1).collect::<Vec<_>>();
    let cases = |w: &[Weight]| w.iter().map(|w| w.2).collect::<Vec<_>>();
    letters(&wa)
        .cmp(&letters(&wb))
        .then_with(|| accents(&wa).cmp(&accents(&wb)))
        .then_with(|| cases(&wa).cmp(&cases(&wb)))
}

